def binary_to_hex(bin_str):
    # Convert binary string to hexadecimal
    hex_str = hex(int(str(bin_str), 2))[2:]
    hex_str = hex_str.zfill(8)
    return hex_str.upper()

def hex_to_bin(hex_str):
    # Convert hex str to bin
    bin_str = bin(int(str(hex_str), 16))[2:]
    bin_str = bin_str.zfill(32)
    return bin_str.upper()

def read_cache(cache_data, line):
    # cache_data is a packed [127:0][31:0] array; word 0 occupies the
    # most-significant 32 bits in cocotb's flattened representation.
    upper = 32 * (129 - line) - 1
    lower = 32 * (128 - line)
    return int(cache_data.value[lower:upper])

