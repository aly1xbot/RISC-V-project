async def cpu_reset(dut):
    # Reset is generated by cpu_harness so Verilator owns the top-level
    # reset nets.  Wait until the synchronous CPU reset has been released.
    await Timer(25, units="ns")
    assert int(dut.rst_n.value) == 1, "CPU reset did not de-assert"



